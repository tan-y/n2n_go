#!/usr/bin/env bash
# Build libn2n.a for Windows/amd64 from the bundled n2n source tree.
#
# Run this inside an MSYS2 MinGW-w64 shell:
#   pacman -S --needed mingw-w64-x86_64-gcc make autoconf automake libtool pkg-config patch rsync
#   ./scripts/build-n2n-win.sh
#
# N2N_SRC may point at a different checkout; it defaults to the submodule.

set -euo pipefail

case "$(uname -s)" in
  MINGW*|MSYS*|CYGWIN*) ;;
  *) echo "请在 Windows 的 MSYS2 MinGW x64 shell 中构建 (run this script inside an MSYS2 MinGW-w64 shell)" >&2; exit 2 ;;
esac

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
N2N_SRC="${N2N_SRC:-$ROOT/third_party/n2n}"
WORK="$ROOT/build/n2n-windows-amd64"
LIB_DIR="$ROOT/third_party/lib/windows/amd64"
INCLUDE_DIR="$ROOT/third_party/n2n-src/include"

if [ ! -d "$N2N_SRC" ]; then
  echo "n2n source not found: $N2N_SRC (run: git submodule update --init third_party/n2n)" >&2
  exit 2
fi

for tool in gcc ar windres make autoconf automake pkg-config patch rsync; do
  if ! command -v "$tool" >/dev/null 2>&1; then
    echo "missing build tool: $tool (use the MSYS2 MinGW-w64 shell)" >&2
    exit 2
  fi
done

case "$(gcc -dumpmachine)" in
  x86_64-w64-mingw32) ;;
  *) echo "gcc is not targeting x86_64-w64-mingw32: $(gcc -dumpmachine)" >&2; exit 2 ;;
esac

echo "==> preparing $WORK from $N2N_SRC"
rm -rf "$WORK"
mkdir -p "$WORK"
# The n2n tree ships packaging symlinks (packages/centos -> rpm) that rsync
# cannot recreate on Windows; the library build does not need them.
rsync -a --exclude build --exclude bin --exclude .git --exclude packages "$N2N_SRC/" "$WORK/"

echo "==> installing wintun device layer"
cp "$ROOT/platform/windows/tuntap_wintun.c" "$WORK/src/win32/wintap.c"
cp "$ROOT/platform/windows/tuntap_wintun.h" "$WORK/src/win32/tuntap_wintun.h"

echo "==> applying patches"
(
  cd "$WORK"
  patch -p1 --quiet -i "$ROOT/patches/n2n-keep-running.patch"
  patch -p1 --quiet -i "$ROOT/patches/n2n-win32-wintun.patch"
)

echo "==> autogen + configure (x86_64-w64-mingw32)"
(
  cd "$WORK"
  ./autogen.sh
  ./configure \
    --host=x86_64-w64-mingw32 \
    CC=gcc AR=ar WINDRES=windres \
    CFLAGS="-O2 -Wall -D_WIN32_WINNT=0x0601 -DSKIP_MULTICAST_PEERS_DISCOVERY" \
    LDFLAGS="-static"
)

echo "==> building libn2n.a"
make -C "$WORK" libn2n.a

if ! ar t "$WORK/libn2n.a" | grep -q '^wintap\.o$'; then
  echo "libn2n.a does not contain wintap.o; the win32 source set changed" >&2
  exit 1
fi

echo "==> installing artifacts"
mkdir -p "$LIB_DIR" "$(dirname "$INCLUDE_DIR")" "$ROOT/bin"
cp "$WORK/libn2n.a" "$LIB_DIR/libn2n.a"

# config.h is generated by configure; its content is equivalent across platforms
# but carries a build timestamp, so do not let the Windows copy overwrite the
# shared one (it would force a full rebuild on macOS/Linux). Only add it when
# the shared directory does not have it yet.
mkdir -p "$INCLUDE_DIR"
rsync -a --exclude config.h "$WORK/include/" "$INCLUDE_DIR/"
if [ ! -f "$INCLUDE_DIR/config.h" ]; then
  cp "$WORK/include/config.h" "$INCLUDE_DIR/config.h"
fi

# n2n_typedefs.h includes "../src/win32/n2n_win32.h" when targeting MinGW, so the
# win32 headers must sit next to include/ in the shared cgo header tree.
WIN32_INCLUDE_DIR="$(dirname "$INCLUDE_DIR")/src/win32"
mkdir -p "$WIN32_INCLUDE_DIR"
rsync -a --include '*/' --include '*.h' --exclude '*' \
  "$WORK/src/win32/" "$WIN32_INCLUDE_DIR/"

echo "==> done"
ls -l "$LIB_DIR/libn2n.a"
